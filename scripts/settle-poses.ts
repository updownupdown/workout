// Bake floor-contact settling for every keyframe into src/data/settled.ts.
// Usage: npx tsx scripts/settle-poses.ts
import { writeFileSync } from 'node:fs'
import { RAW_MOVES } from '../src/data/moves'
import { FLOOR } from '../src/data/contacts'
import { full, NEUTRAL, Pose } from '../src/figure/skeleton'
import { contactGaps, settle } from '../src/figure/settle'

const out: Record<string, (Partial<Pose> | null)[]> = {}
let worst = 0
for (const m of RAW_MOVES) {
  const cs = FLOOR[m.id]
  if (!cs) continue
  out[m.id] = m.anim.frames.map((f, i) => {
    const c = cs[i]
    if (!c || c.length === 0) return null
    const p0 = full(f)
    const p = settle(p0, m.anim.view, c)
    const gaps = contactGaps(p, m.anim.view, c)
    const g = Math.max(...gaps)
    worst = Math.max(worst, g)
    if (g > 2.5) console.log(`${m.id} f${i}: residual gap ${g.toFixed(1)} (${c.join(',')})`)
    const diff: Partial<Pose> = { rot: Math.round(p.rot * 2) / 2 }
    for (const k of Object.keys(NEUTRAL) as (keyof Pose)[]) {
      if (k === 'rot') continue
      const v = Math.round(p[k] * 2) / 2
      if (Math.abs(v - p0[k]) >= 0.5) diff[k] = v
    }
    return diff
  })
}
const body = JSON.stringify(out, null, 0).replace(/\],"/g, '],\n  "')
writeFileSync(
  new URL('../src/data/settled.ts', import.meta.url),
  `// Generated by scripts/settle-poses.ts. Do not edit by hand.\nimport type { PoseInput } from '../figure/skeleton'\n\nexport const SETTLED: Record<string, (PoseInput | null)[]> = ${body}\n`,
)
console.log(`settled ${Object.keys(out).length} moves, worst residual ${worst.toFixed(1)}`)
