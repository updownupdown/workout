/**
 * Settle every move's keyframes on the real 3D bodies (balance, contacts,
 * clipping, joint limits) and write src/data/settled3d.ts.
 *
 *   npx vite --port 5173 &   # dev server
 *   node scripts/realistic/bake-poses.cjs [ids]     # all moves, or a comma list (merged into the file)
 *
 * Uses Playwright's Chromium with software WebGL.
 */
const { chromium } = require('playwright')
const fs = require('fs')
const path = require('path')

const OUT = path.join(__dirname, '../../src/data/settled3d.ts')
const BASE = process.env.BASE || 'http://localhost:5173/workout/'

function readExisting() {
  try {
    const s = fs.readFileSync(OUT, 'utf8')
    const j = s.slice(s.indexOf('= {') + 2).trim()
    return JSON.parse(j)
  } catch {
    return {}
  }
}

;(async () => {
  const ids = process.argv[2] || ''
  const chars = (process.env.CHARS || 'ava,leo').split(',')
  const all = readExisting()
  const b = await chromium.launch({ args: ['--use-angle=swiftshader', '--enable-unsafe-swiftshader', '--ignore-gpu-blocklist'] })
  for (const c of chars) {
    const p = await b.newPage({ viewport: { width: 200, height: 200 } })
    p.on('pageerror', (e) => console.log('pageerror', e.message))
    await p.goto(`${BASE}realistic.html?c=${c}&q=lite`)
    await p.waitForFunction(() => document.querySelector('.loading')?.hidden, null, { timeout: 60000 })
    const list = ids ? ids.split(',') : await p.evaluate(() => Object.keys(window.__moves))
    all[c] = all[c] || {}
    for (const id of list) {
      const r = await p.evaluate(async (id) => {
        const P = await import('/workout/src/figure/real/physics.ts')
        const S = await import('/workout/src/figure/skeleton.ts')
        const real = window.__real
        real.autoTime = false
        const d = real.driver
        if (!window.__ph) {
          window.__ph = new P.Physics(d)
          d.pose({ ...S.NEUTRAL }, 'side')
          window.__ph.fitCapsules()
        }
        const ph = window.__ph
        const m = window.__moves[id]
        const F = await import('/workout/src/data/poses3d.ts')
        const anim = { ...F.for3D(m.anim), id: undefined }
        const comp = d.compile(anim)
        const t0 = performance.now()
        const frames = comp.poses.map((pose, i) => {
          d.pose(pose, anim.view)
          const contacts = P.contactsFor(anim, i, pose) ?? ph.touching()
          const res = ph.settle(pose, anim.view, contacts)
          d.pose(res.pose, anim.view)
          const ms = ph.measure(contacts, res.pose)
          const diff = { rot: Math.round(res.pose.rot * 2) / 2 }
          for (const k of Object.keys(S.NEUTRAL)) {
            const v = Math.round(res.pose[k] * 2) / 2
            const src = anim.frames[i][k] ?? 0
            if (k !== 'rot' && Math.abs(v - src) >= 0.5) diff[k] = v
          }
          return {
            diff, before: +res.before.toFixed(1), after: +res.after.toFixed(1),
            bal: +ms.balance.toFixed(1), clips: ms.clips.length, float: ms.gaps.filter((g) => g.gap > 1.5).length,
          }
        })
        return { frames, ms: Math.round(performance.now() - t0) }
      }, id)
      all[c][id] = r.frames.map((f) => f.diff)
      console.log(c, id, r.ms + 'ms', r.frames.map((f) => `E ${f.before}->${f.after} bal ${f.bal} clip ${f.clips} float ${f.float}`).join(' | '))
    }
    await p.close()
  }
  await b.close()
  const body = JSON.stringify(all)
    .replace(/\],"/g, '],\n    "')
    .replace(/\},"/g, '},\n  "')
  fs.writeFileSync(
    OUT,
    `// Generated by scripts/realistic/bake-poses.cjs. Do not edit by hand.\nimport type { PoseInput } from '../figure/skeleton'\n\n/** Per body, per move: keyframe adjustments found by the 3D settle (figure/real/physics.ts). */\nexport const SETTLED3D: Record<string, Record<string, PoseInput[]>> = ${body}\n`,
  )
})()
